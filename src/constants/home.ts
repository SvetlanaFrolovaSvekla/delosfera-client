// Высота верхней пары карточек - "Мои задачи" (MyTasksCard) и "План актуализации ВНД"
// (ActualizationPlanCard). Раньше обе карточки лежали в одной строке грида без явной высоты и
// растягивались по умолчанию (align-items: stretch) до высоты более высокой из них - из-за
// этого "План актуализации" (компактная сетка из 4 показателей) раздувался вровень с "Мои
// задачи" (которая при большом числе задач всегда заметно выше), и снизу оставалось пустое
// белое место. В HomePage.tsx грид теперь с items-start (каждая карточка сама решает свою
// высоту), а обе карточки берут одну и ту же фиксированную высоту отсюда - так они гарантированно
// совпадают по размеру, а не "плюс-минус похожи" (см. MyTasksCard.tsx/ActualizationPlanCard.tsx -
// header в обеих flex-none, оставшееся место каждая карточка занимает по-своему: у "Плана" -
// центрированием сетки показателей, у "Мои задачи" - скроллом списка).
